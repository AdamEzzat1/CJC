/// Distance from `got` to `want` in units of ulp(want) (subnormal spacing for
/// subnormal/zero `want`).
fn ulps(got: f64, want: f64) -> f64 {
    let a = want.abs();
    let ulp = if a < f64::MIN_POSITIVE {
        f64::from_bits(1)
    } else {
        f64::from_bits(a.to_bits() + 1) - a
    };
    (got - want).abs() / ulp
}

fn check_ulps(name: &str, f: fn(f64) -> f64, table: &[(f64, f64)], max_ulps: f64) -> f64 {
    let mut worst = 0.0f64;
    let mut failures = Vec::new();
    for &(x, want) in table {
        let got = f(x);
        let u = ulps(got, want);
        worst = worst.max(u);
        if !(u <= max_ulps) {
            failures.push(format!("{name}({x:e}) = {got:e}, mpmath {want:e}, {u:.3e} ulp"));
        }
    }
    eprintln!("{name}: {} points, worst {worst:.3} ulp", table.len());
    assert!(failures.is_empty(), "{} failures:\n{}", failures.len(), failures.join("\n"));
    worst
}

