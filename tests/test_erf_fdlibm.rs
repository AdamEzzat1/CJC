#[test]
fn erf_special_values() {
    assert_eq!(erf(0.0).to_bits(), 0.0f64.to_bits());
    assert_eq!(erf(-0.0).to_bits(), (-0.0f64).to_bits(), "erf(-0) must be -0");
    assert_eq!(erfc(0.0), 1.0);
    assert_eq!(erfc(-0.0), 1.0);
    assert_eq!(erf(f64::INFINITY), 1.0);
    assert_eq!(erf(f64::NEG_INFINITY), -1.0);
    assert_eq!(erfc(f64::INFINITY), 0.0);
    assert_eq!(erfc(f64::NEG_INFINITY), 2.0);
    assert!(erf(f64::NAN).is_nan());
    assert!(erfc(f64::NAN).is_nan());
    assert!(normal_cdf(f64::NAN).is_nan());
    assert_eq!(normal_cdf(f64::INFINITY), 1.0);
    assert_eq!(normal_cdf(f64::NEG_INFINITY), 0.0);
    assert_eq!(normal_cdf(0.0), 0.5);
    // Far tails: erfc underflows to +0 for x >= 28, erf saturates to +-1.
    assert_eq!(erfc(28.0), 0.0);
    assert_eq!(erfc(1e10), 0.0);
    assert_eq!(erf(1e10), 1.0);
    assert_eq!(erf(-1e10), -1.0);
    // erf is odd, bit for bit.
    for i in 1..200 {
        let x = i as f64 * 0.037;
        assert_eq!(erf(-x).to_bits(), (-erf(x)).to_bits(), "erf odd at {x}");
    }
}

#[test]
fn normal_cdf_lower_tail_has_no_cancellation() {
    let mut worst = 0.0f64;
    for &(x, want) in NCDF {
        let got = normal_cdf(x);
        if want < f64::MIN_POSITIVE {
            // Subnormal result: absolute error a few subnormal units.
            assert!(ulps(got, want) <= 64.0, "normal_cdf({x}) = {got:e} vs {want:e}");
            continue;
        }
        let rel = (got - want).abs() / want;
        let bound = (4.0 + 2.0 * x * x) * f64::EPSILON;
        worst = worst.max(rel / bound);
        assert!(rel <= bound, "normal_cdf({x}) = {got:e}, mpmath {want:e}, rel {rel:e} > {bound:e}");
    }
    eprintln!("normal_cdf: worst rel err / bound = {worst:.3}");
}

#[test]
fn erf_is_bit_deterministic() {
    let xs: Vec<f64> = (0..2000).map(|i| -7.0 + i as f64 * 0.0173).collect();
    let a: Vec<u64> = xs.iter().map(|&x| erf(x).to_bits() ^ erfc(x).to_bits().rotate_left(1) ^ normal_cdf(x).to_bits().rotate_left(2)).collect();
    for _ in 0..3 {
        let b: Vec<u64> = xs.iter().map(|&x| erf(x).to_bits() ^ erfc(x).to_bits().rotate_left(1) ^ normal_cdf(x).to_bits().rotate_left(2)).collect();
        assert_eq!(a, b);
    }
}

// ---- executor parity --------------------------------------------------------

fn run_eval(src: &str, seed: u64) -> Vec<String> {
    let (program, _diag) = cjc_parser::parse_source(src);
    let mut interp = cjc_eval::Interpreter::new(seed);
    let _ = interp.exec(&program);
    interp.output
}

fn run_mir(src: &str, seed: u64) -> Vec<String> {
    let (program, _diag) = cjc_parser::parse_source(src);
    let (_, executor) = cjc_mir_exec::run_program_with_executor(&program, seed)
        .unwrap_or_else(|e| panic!("MIR-exec failed: {e}"));
    executor.output
}

fn assert_parity(src: &str) -> Vec<String> {
    let eval_out = run_eval(src, 42);
    let mir_out = run_mir(src, 42);
    assert_eq!(eval_out, mir_out, "Parity mismatch!\nEval: {eval_out:?}\nMIR:  {mir_out:?}");
    eval_out
}

const PARITY_SRC: &str = r#"
fn main() {
    let mut i: i64 = -30;
    while i <= 30 {
        let x: f64 = float(i) / 5.0;
        print(erf(x));
        print(erfc(x));
        print(normal_cdf(x));
        i = i + 1;
    }
    print(erfc(26.0));
    print(normal_cdf(-37.0));
    print(erf(0.5));
    print(erfc(5.0));
}
"#;

#[test]
fn erf_parity_eval_vs_mir() {
    let out = assert_parity(PARITY_SRC);
    assert_eq!(out.len(), 61 * 3 + 4, "unexpected output: {out:?}");
    // Values printed by the language must be the runtime's values bit for bit.
    let erf_half: f64 = out[61 * 3 + 2].parse().unwrap();
    assert_eq!(erf_half.to_bits(), erf(0.5).to_bits());
    let erfc5: f64 = out[61 * 3 + 3].parse().unwrap();
    assert_eq!(erfc5.to_bits(), erfc(5.0).to_bits());
}

#[test]
fn erf_parity_output_is_deterministic() {
    assert_eq!(assert_parity(PARITY_SRC), assert_parity(PARITY_SRC));
}
